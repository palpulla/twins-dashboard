import { createServer } from 'node:http';
import { createReadStream, existsSync, statSync } from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
const ROOT=process.argv[2], PAGE=process.argv[3];
const mime=new Map([['.html','text/html; charset=utf-8'],['.css','text/css; charset=utf-8'],['.js','text/javascript; charset=utf-8'],['.png','image/png'],['.jpg','image/jpeg'],['.jpeg','image/jpeg'],['.webp','image/webp'],['.woff2','font/woff2'],['.json','application/json']]);
const server=createServer((req,res)=>{const p=path.join(ROOT,decodeURIComponent(req.url.split('?')[0]));if(!p.startsWith(ROOT)||!existsSync(p)||!statSync(p).isFile()){res.writeHead(404);res.end();return;}res.writeHead(200,{'Content-Type':mime.get(path.extname(p))||'application/octet-stream'});createReadStream(p).pipe(res);});
await new Promise(r=>server.listen(41996,'127.0.0.1',r));
const browser=await chromium.launch();
const ctx=await browser.newContext({viewport:{width:1440,height:900}});
const page=await ctx.newPage();
const errs=[]; page.on('pageerror',e=>errs.push(String(e))); page.on('console',m=>{if(m.type()==='error')errs.push(m.text());});
await page.goto(`http://127.0.0.1:41996/${PAGE}`,{waitUntil:'load'});
const res={errs};
res.scriptRan = await page.evaluate(()=>!!document.querySelector('.twins-brand-nav-trigger'));
await page.evaluate(()=>{const t=[...document.querySelectorAll('.twins-brand-nav-trigger')].pop();t.focus();});
res.beforeExpanded = await page.evaluate(()=>[...document.querySelectorAll('.twins-brand-nav-trigger')].pop().getAttribute('aria-expanded'));
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(300);
res.afterExpanded = await page.evaluate(()=>[...document.querySelectorAll('.twins-brand-nav-trigger')].pop().getAttribute('aria-expanded'));
res.active = await page.evaluate(()=>({tag:document.activeElement.tagName,cls:String(document.activeElement.className).slice(0,50),text:document.activeElement.textContent.trim().slice(0,26)}));
// now try arrow-walking from an explicitly focused first link
await page.evaluate(()=>{const t=[...document.querySelectorAll('.twins-brand-nav-trigger')].pop();const p=t.nextElementSibling;p.querySelector('a[href]').focus();});
res.afterManualFocus = await page.evaluate(()=>document.activeElement.textContent.trim().slice(0,26));
await page.keyboard.press('ArrowDown'); await page.waitForTimeout(80);
res.arrowDown1 = await page.evaluate(()=>document.activeElement.textContent.trim().slice(0,26));
await page.keyboard.press('End'); await page.waitForTimeout(80);
res.endKey = await page.evaluate(()=>document.activeElement.textContent.trim().slice(0,26));
await page.keyboard.press('Home'); await page.waitForTimeout(80);
res.homeKey = await page.evaluate(()=>document.activeElement.textContent.trim().slice(0,26));
await page.keyboard.press('Escape'); await page.waitForTimeout(120);
res.afterEscape = await page.evaluate(()=>({active:document.activeElement.textContent.trim().slice(0,26),expanded:[...document.querySelectorAll('.twins-brand-nav-trigger')].pop().getAttribute('aria-expanded')}));
console.log(JSON.stringify(res,null,1));
await browser.close(); server.close();
